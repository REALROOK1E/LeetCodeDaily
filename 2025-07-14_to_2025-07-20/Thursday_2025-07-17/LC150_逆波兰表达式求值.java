import java.util.*;

/**
 * LeetCode 150 - 逆波兰表达式求值
 * 
 * 题目描述：
 * 根据逆波兰表示法，求表达式的值。
 * 
 * 有效的算符包括 +、-、*、/ 。每个运算对象可以是整数，也可以是另一个逆波兰表达式。
 * 
 * 注意 两个整数之间的除法只保留整数部分。
 * 
 * 可以保证给定的逆波兰表达式总是有效的。换句话说，表达式总会得出有效数值且不存在除数为零的情况。
 * 
 * 示例：
 * 输入：tokens = ["2","1","+","3","*"]
 * 输出：9
 * 解释：该算式转化为常见的中缀算术表达式为：((2 + 1) * 3) = 9
 * 
 * 输入：tokens = ["4","13","5","/","+"]
 * 输出：6
 * 解释：该算式转化为常见的中缀算术表达式为：(4 + (13 / 5)) = 6
 * 
 * 输入：tokens = ["10","6","9","3","+","-11","*","/","*","17","+","5","+"]
 * 输出：22
 * 解释：该算式转化为常见的中缀算术表达式为：
 *   ((10 * (6 / ((9 + 3) * -11))) + 17) + 5
 * = ((10 * (6 / (12 * -11))) + 17) + 5
 * = ((10 * (6 / -132)) + 17) + 5
 * = ((10 * 0) + 17) + 5
 * = (0 + 17) + 5
 * = 17 + 5
 * = 22
 * 
 * 提示：
 * 1 <= tokens.length <= 10^4
 * tokens[i] 是一个算符（"+"、"-"、"*"、"/"），或是在范围 [-200, 200] 内的一个整数
 * 
 * 逆波兰表达式：
 * 逆波兰表达式是一种后缀表达式，所谓后缀就是指算符写在后面。
 * 
 * 平常使用的算式则是一种中缀表达式，如 ( 1 + 2 ) * ( 3 + 4 ) 。
 * 该算式的逆波兰表达式写法为 ( ( 1 2 + ) ( 3 4 + ) * ) 。
 
 */
public class LC150_逆波兰表达式求值 {
    
    /**
     * 方法3：数组模拟栈
     * 时间复杂度：O(n)
     * 空间复杂度：O(n)
     */
    public static int evalRPN(String[] tokens) {
        // 遇到运算符号——取出来两个——计算后入栈，遇到数字直接入栈
        int r=0;
        int [] q=new int [tokens.length];
        int ans=0;
        for (int i = 0; i < q.length; i++) {
         
                switch (tokens[i]) {
                case "+":
                     ans= q[--r]+q[--r];
                     q[r++]=ans;
                    break;
            
                case "-":
                ans= q[r-2]-q[r-1];
                         r-=2;
                         q[r++]=ans;
                      break;
                case "*":
                ans= q[--r]*q[--r];
                    q[r++]=ans;
                      break;
                case "/":
                ans= q[r-2]/q[r-1];
                       r-=2;
                       q[r++]=ans;
                     break;
                default: q[r++]=Integer.parseInt(tokens[i]);
                }
            
        }
        return q[0];
    }
    public static void main(String[] args) {

        // 测试用例
        String[][] testCases = {
            {"2", "1", "+", "3", "*"},                    // 期望输出: 9
            {"4", "13", "5", "/", "+"},                   // 期望输出: 6
            {"10", "6", "9", "3", "+", "-11", "*", "/", "*", "17", "+", "5", "+"}, // 期望输出: 22
            {"4", "3", "-"},                              // 期望输出: 1
            {"3", "4", "+", "2", "*", "1", "+"},         // 期望输出: 15
            {"1", "2", "+", "3", "4", "+", "*"},         // 期望输出: 21
            {"18"},                                       // 期望输出: 18
            {"2", "1", "+", "3", "*", "4", "5", "+", "*"} // 期望输出: 54
        };
        
        for (int i = 0; i < testCases.length; i++) {
            String[] tokens = testCases[i];
            int result = evalRPN(tokens);
            System.out.println("测试用例 " + (i + 1) + ":");
            System.out.println("输入: " + Arrays.toString(tokens));
            System.out.println("输出: " + result);
            System.out.println("---");
        }
    }
} 